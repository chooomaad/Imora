// Copies the platform-agnostic parts of @imora/shared into the Edge Functions tree
// (Deno cannot resolve the npm workspace). Run: npm run sync:edge
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = path.join(root, "packages/shared/src");
const dst = path.join(root, "supabase/functions/_shared/generated");
fs.mkdirSync(dst, { recursive: true });

for (const file of ["domain.ts", "filters.ts", "geo.ts"]) {
  let code = fs.readFileSync(path.join(src, file), "utf8");
  // Deno needs explicit specifiers
  code = code.replace(/from "zod"/g, 'from "npm:zod@3.25.76"').replace(/from "\.\/(\w+)"/g, 'from "./$1.ts"');
  fs.writeFileSync(path.join(dst, file), `// GENERATED by scripts/sync-edge-shared.mjs — do not edit. Source: packages/shared/src/${file}\n${code}`);
}
console.log("Synced shared domain/filters/geo into supabase/functions/_shared/generated");
